/// Generates consolidated TypeScript type definitions for all IPC models using `ts-rs`
pub fn generate_typescript_bindings() -> String {
    let decls = [
        CoreType::decl(),
        ProtocolType::decl(),
        TransportKind::decl(),
        TransportConfig::decl(),
        RealityConfig::decl(),
        TlsConfig::decl(),
        ShadowsocksConfig::decl(),
        ShadowsocksRConfig::decl(),
        VmessConfig::decl(),
        VlessConfig::decl(),
        TrojanConfig::decl(),
        HysteriaConfig::decl(),
        Hysteria2Config::decl(),
        TuicConfig::decl(),
        WireGuardConfig::decl(),
        AnyTlsConfig::decl(),
        ShadowTlsConfig::decl(),
        NaiveConfig::decl(),
        SnellConfig::decl(),
        MieruConfig::decl(),
        SshConfig::decl(),
        Socks5Config::decl(),
        HttpConfig::decl(),
        ProtocolConfig::decl(),
        ProxyNode::decl(),
        Subscription::decl(),
        GroupType::decl(),
        NodeGroup::decl(),
        LatencyRecord::decl(),
        RoutingMode::decl(),
        LogLevel::decl(),
        AppSettings::decl(),
        LogStream::decl(),
        CoreLogEntry::decl(),
        CoreLifecycleState::decl(),
        CoreStatusInfo::decl(),
        CoreStartRequest::decl(),
        CapabilityRule::decl(),
        CoreCapabilities::decl(),
        SelectionReason::decl(),
        CoreSelection::decl(),
        CoreLockEntry::decl(),
        CoreUpdateCheckResult::decl(),
        CoreUpdateResult::decl(),
        SubscriptionFormat::decl(),
        SubscriptionParseReport::decl(),
        SubscriptionUserInfo::decl(),
    ];

    let mut out = String::from(
        "// AUTO-GENERATED BY ts-rs FROM src-tauri/src/model/mod.rs — DO NOT EDIT MANUALLY\n\n",
    );
    for decl in decls {
        out.push_str("export ");
        out.push_str(decl.trim());
        out.push_str("\n\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn test_export_typescript_bindings() {
        let content = generate_typescript_bindings();
        assert!(content.contains("export type ProxyNode ="));
        assert!(content.contains("export type Subscription ="));
        assert!(content.contains("export type AppSettings ="));
        assert!(content.contains("export type RoutingMode ="));
        assert!(content.contains("export type CoreLifecycleState ="));
        assert!(content.contains("export type CoreStatusInfo ="));

        let out_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .join("src")
            .join("types")
            .join("bindings.ts");
        if let Some(parent) = out_path.parent() {
            std::fs::create_dir_all(parent).unwrap();
        }
        std::fs::write(&out_path, content).unwrap();
    }
}
